if __name__ == "__main__":
    want = page()
    if "--check" in sys.argv:
        have = io.open(OUT, encoding="utf-8").read() if os.path.isfile(OUT) else ""
        if have != want:
            print("chapters.html is stale -- run python tools/build_chapters_page.py")
            sys.exit(1)
        print("chapters.html matches the lessons")
        sys.exit(0)
    io.open(OUT, "w", encoding="utf-8", newline="\n").write(want)
    print("wrote chapters.html")
