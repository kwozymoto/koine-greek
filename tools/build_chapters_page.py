# -*- coding: utf-8 -*-
"""chapters.html -- what each of the 27 chapters teaches, as a plain page.

    python tools/build_chapters_page.py            # write chapters.html
    python tools/build_chapters_page.py --check    # exit 1 if it is stale

WHY. The app draws its chapters with JavaScript, so a search engine sees none
of them. Someone searching for "second aorist" or "genitive absolute" should
be able to find a page that says which chapter teaches it. This page lists
each chapter's title, its one-line summary and the headings inside it -- the
topics as the chapter itself names them.

GENERATED, NEVER EDITED BY HAND. Everything on it comes from data/lessons.js
(title, summary, headings, number of parts) and data/lesson_audio.js (which
chapters are read aloud), so it cannot say something the chapters do not.
check_chapters_page runs this with --check and fails when a lesson has changed
and the page has not been rebuilt.
"""
import html
import io
import json
import os
import re
import subprocess
import sys

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "chapters.html")

TAG = re.compile(r"<[^>]+>")
HEAD = re.compile(r"<(h2|h3)\b[^>]*>(.*?)</\1>", re.S)


def lessons():
    js = ("const fs=require('fs'),vm=require('vm');const c=vm.createContext({});"
          "vm.runInContext(fs.readFileSync('data/lessons.js','utf8'),c);"
          "process.stdout.write(vm.runInContext('JSON.stringify(LESSONS.map("
          "l=>({id:l.id,t:l.t,s:l.s,body:l.body})))',c));")
    r = subprocess.run(["node", "-e", js], cwd=ROOT, capture_output=True,
                       text=True, encoding="utf-8")
    if r.returncode or not r.stdout:
        sys.exit("could not read data/lessons.js:\n" + (r.stderr or ""))
    return json.loads(r.stdout)


def narrated():
    """Chapters with narration, from the file the app loads."""
    p = os.path.join(ROOT, "data", "lesson_audio.js")
    if not os.path.isfile(p):
        return set()
    s = io.open(p, encoding="utf-8").read()
    m = re.search(r"const LESSON_AUDIO = (\[.*\]);\s*$", s, re.S)
    return {r["ch"] for r in json.loads(m.group(1))} if m else set()


def text(fragment):
    return " ".join(html.unescape(TAG.sub(" ", fragment)).split())


def page():
    ls = lessons()
    aloud = narrated()
    items = []
    for l in ls:
        heads = [text(h) for _t, h in HEAD.findall(l["body"])]
        heads = [h for h in dict.fromkeys(heads) if h]
        parts = len(HEAD.findall(l["body"])) + 1
        badge = ('<span class="badge">Read aloud</span>'
                 if l["id"] in aloud else "")
        topics = ("<ul>%s</ul>" % "".join("<li>%s</li>" % html.escape(h)
                                          for h in heads)) if heads else ""
        items.append(
            '<section class="ch" id="chapter-%d">\n'
            '  <h2><span class="n">Chapter %d</span> %s %s</h2>\n'
            '  <p class="s">%s</p>\n  %s\n</section>'
            % (l["id"], l["id"], html.escape(l["t"]), badge,
               html.escape(l["s"] or ""), topics))
    return TEMPLATE % {"count": len(ls), "aloud": len(aloud),
                       "items": "\n".join(items)}


